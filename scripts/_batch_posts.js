// ── 순차 처리 ──────────────────────────────────────────────────────────────────
async function runPost(post) {
  const { sectionId, dateOverride, topic, outline, body, imgPrompts } = post;
  return new Promise((resolve, reject) => {
    const child = spawn(process.execPath, [SAVE_POST], {
      cwd: ROOT,
      stdio: ['pipe', 'pipe', 'inherit'],
    });
    child.stdin.write(JSON.stringify({ sectionId, topic, outline, body, imgPrompts, dateOverride }));
    child.stdin.end();
    let out = '';
    child.stdout.on('data', d => { out += d; });
    child.on('close', code => {
      if (code === 0) {
        try {
          const lastLine = out.trim().split('\n').pop();
          resolve(JSON.parse(lastLine));
        } catch { resolve({ ok: true, raw: out.slice(-200) }); }
      } else {
        reject(new Error(`exit ${code}`));
      }
    });
    child.on('error', reject);
  });
}

async function runAll() {
  for (const post of posts) {
    console.error(`\n📰  [${post.sectionId}] ${post.topic.title}`);
    try {
      const result = await runPost(post);
      console.error(`✅  완료: ${result.postPath ?? result.slug ?? 'ok'}`);
    } catch (err) {
      console.error(`❌  실패: ${err.message}`);
    }
  }
  console.error('\n🎉  전체 배치 완료!');
}

